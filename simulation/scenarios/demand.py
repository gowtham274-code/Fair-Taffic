"""Traffic-demand scenarios and deterministic demand generation.

Demand is generated by this module (not by SUMO) so that a given (scenario, seed,
duration, scale) always yields the same vehicle list, and every controller and both
backends see exactly the same traffic.

Rates are vehicles per hour per ENTRY edge, keyed by the side of the network the
entry is on. Values are engineering defaults for a single-lane grid (adjust in the
config / this table and re-validate): they are not taken from the source documents.
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Tuple

import numpy as np

from simulation.network.topology import NetTopology

SCENARIO_RATES: Dict[str, Dict[str, float]] = {
    "low": {"N": 100, "E": 100, "S": 100, "W": 100},
    "medium": {"N": 250, "E": 250, "S": 250, "W": 250},
    "high": {"N": 400, "E": 400, "S": 400, "W": 400},
    # uneven: the west side receives 4x the flow of the north/south/east sides
    "uneven": {"N": 150, "E": 150, "S": 150, "W": 600},
}


@dataclass(frozen=True)
class Vehicle:
    vid: str
    depart: int
    route: Tuple[str, ...]


def generate_demand(
    topo: NetTopology, scenario: str, duration_s: int, seed: int, scale: float = 1.0
) -> List[Vehicle]:
    """Poisson arrivals at every entry edge, shortest-path route to a random exit."""
    if scenario not in SCENARIO_RATES:
        raise ValueError(f"unknown scenario {scenario!r}; choose from {sorted(SCENARIO_RATES)}")
    rng = np.random.default_rng(seed)
    exits = topo.exit_edges()
    raw: List[Tuple[int, Tuple[str, ...]]] = []
    for entry, side in topo.entry_edges():
        rate = SCENARIO_RATES[scenario][side] * scale
        n = int(rng.poisson(rate * duration_s / 3600.0))
        departs = np.sort(rng.integers(0, duration_s, size=n))
        entry_from = topo.edges[entry][0]
        candidates = [x for x in exits if topo.edges[x][1] != entry_from]
        for d in departs:
            for _ in range(10):  # retry until a routable exit is drawn
                ex = candidates[int(rng.integers(0, len(candidates)))]
                path = topo.route(entry, ex)
                if path:
                    raw.append((int(d), tuple(path)))
                    break
    raw.sort(key=lambda x: x[0])
    return [Vehicle(f"v{i}", d, r) for i, (d, r) in enumerate(raw)]


def write_route_file(vehicles: List[Vehicle], path: str | Path) -> Path:
    """Write a SUMO route file (vehicles sorted by departure time)."""
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    lines = ['<?xml version="1.0" encoding="UTF-8"?>', "<routes>"]
    lines.append('  <vType id="car" accel="2.6" decel="4.5" sigma="0.5" length="5" minGap="2.5" maxSpeed="13.89"/>')
    for v in vehicles:
        lines.append(
            f'  <vehicle id="{v.vid}" type="car" depart="{v.depart}" departLane="best" departSpeed="max">'
            f'<route edges="{" ".join(v.route)}"/></vehicle>'
        )
    lines.append("</routes>")
    p.write_text("\n".join(lines) + "\n")
    return p
